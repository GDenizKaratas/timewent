export const DICTS: Record<Lang, Record<Key, string>> = { en, tr }

let current: Lang = 'en'
export const lang = (): Lang => current
export function setLang(l: Lang): void {
  current = l
  if (typeof document !== 'undefined') document.documentElement.lang = l
  for (const fn of listeners) fn()
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return DICTS[current][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))
}

/** system → the first preferred OS language: tr → tr, anything else → en. */
export function resolveLang(pref: LangPref, preferred: readonly string[]): Lang {
  if (pref !== 'system') return pref
  return preferred[0]?.toLowerCase().startsWith('tr') ? 'tr' : 'en'
}

// Static chrome (built once) registers here and is relabelled when the language changes.
const listeners = new Set<() => void>()
export function onLangChange(fn: () => void): void {
  listeners.add(fn)
}

/** A text node that follows the language. */
export function T(key: Key, vars?: Record<string, string | number>): Text {
  const node = document.createTextNode(t(key, vars))
  onLangChange(() => (node.data = t(key, vars)))
  return node
}
